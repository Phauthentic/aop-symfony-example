<?php

declare(strict_types=1);

namespace Phauthentic\AOP\Symfony;

use Phauthentic\AOP\Exception\ProxyGenerationException;
use Phauthentic\AOP\Proxy\ProxyClassName;
use Phauthentic\AOP\Proxy\ProxyClassWriter;

/**
 * Autoloads generated proxy classes from the proxy directories registered in this process.
 *
 * Every woven service definition includes the proxy directory's `autoload.php` (see {@see self::FILE}), which registers
 * that directory, so a proxy class is loadable before its service is instantiated, also during other bundles' boot().
 *
 * With `strip_final`, a directory also maps final classes to copies without `final` (see {@see self::UNFINALIZED_MAP});
 * those are loaded by an autoloader prepended to Composer's, so the copy wins if nothing loaded the class before.
 */
final class ProxyAutoloader
{
    public const FILE = 'autoload.php';
    public const UNFINALIZED_DIR = 'unfinalized';
    public const UNFINALIZED_MAP = 'map.php';

    /** @var array<string, ProxyClassWriter> */
    private static array $writers = [];

    /** @var array<string, array{file: string, source: string}> class => unfinalized copy and original file */
    private static array $unfinalized = [];

    /** @var array<string, string> proxy class => the unfinalized class it extends */
    private static array $proxyTargets = [];

    /** @var array<string, string> class => original file, for classes loaded from their unfinalized copy */
    private static array $loadedUnfinalized = [];

    public static function register(string $dir): void
    {
        if ([] === self::$writers) {
            spl_autoload_register(self::load(...));
        }
        if (isset(self::$writers[$dir])) {
            return;
        }
        self::$writers[$dir] = new ProxyClassWriter($dir);

        $map = $dir.'/'.self::UNFINALIZED_DIR.'/'.self::UNFINALIZED_MAP;
        if (is_file($map)) {
            /** @var array<string, array{file: string, source: string, proxies: list<string>}> $entries */
            $entries = require $map;
            foreach ($entries as $class => $entry) {
                self::unfinalize($class, \dirname($map).'/'.$entry['file'], $entry['source']);
                self::$proxyTargets += array_fill_keys($entry['proxies'], $class);
            }
        }
    }

    /**
     * Loads $class from $copy instead of $source from now on, unless the class is loaded already.
     */
    public static function unfinalize(string $class, string $copy, string $source): void
    {
        if ([] === self::$unfinalized) {
            spl_autoload_register(self::loadUnfinalized(...), true, true);
        }
        self::$unfinalized[$class] = ['file' => $copy, 'source' => $source];
    }

    /**
     * The original file of a class this process loaded from its unfinalized copy, null for any other class.
     */
    public static function originalFile(string $class): ?string
    {
        return self::$loadedUnfinalized[ltrim($class, '\\')] ?? null;
    }

    /**
     * The contents of the file that registers the directory it is placed in.
     */
    public static function fileContents(): string
    {
        return "<?php\n\n// Generated by phauthentic/aop-bundle: registers this directory's proxy classes for autoloading.\n\\".self::class."::register(__DIR__);\n";
    }

    public static function load(string $class): void
    {
        if (!str_starts_with($class, ProxyClassName::NAMESPACE_PREFIX)) {
            return;
        }
        foreach (self::$writers as $writer) {
            if (is_file($file = $writer->pathFor($class))) {
                self::assertTargetIsNotFinal($class);
                require $file;

                return;
            }
        }
    }

    public static function loadUnfinalized(string $class): void
    {
        $entry = self::$unfinalized[$class] ?? null;
        if (null !== $entry && is_file($entry['file'])) {
            require $entry['file'];
            self::$loadedUnfinalized[$class] = $entry['source'];
        }
    }

    /**
     * Declaring the proxy of a final class is a fatal error; fail with an explanation instead.
     */
    private static function assertTargetIsNotFinal(string $proxyClass): void
    {
        $target = self::$proxyTargets[$proxyClass] ?? null;
        if (null !== $target && class_exists($target, false) && !isset(self::$loadedUnfinalized[$target])) {
            throw new ProxyGenerationException(sprintf('Cannot load the AOP proxy "%s": phauthentic_aop.strip_final needs "%s" to be loaded from its copy without "final", but the original was loaded first (before the kernel booted, by opcache preloading, or by the process that compiled the container). Load the class only after the kernel booted, or exclude it from phauthentic_aop.strip_final_include.', $proxyClass, $target));
        }
    }
}
