<?php

declare(strict_types=1);

namespace Phauthentic\AOP\Symfony;

use Phauthentic\AOP\Proxy\ProxyClassName;
use Phauthentic\AOP\Proxy\ProxyClassWriter;

/**
 * Autoloads generated proxy classes from the proxy directories registered in this process.
 *
 * Every woven service definition includes the proxy directory's `autoload.php` (see {@see self::FILE}), which registers
 * that directory, so a proxy class is loadable before its service is instantiated, also during other bundles' boot().
 */
final class ProxyAutoloader
{
    public const FILE = 'autoload.php';

    /** @var array<string, ProxyClassWriter> */
    private static array $writers = [];

    public static function register(string $dir): void
    {
        if ([] === self::$writers) {
            spl_autoload_register(self::load(...));
        }
        self::$writers[$dir] ??= new ProxyClassWriter($dir);
    }

    /**
     * The contents of the file that registers the directory it is placed in.
     */
    public static function fileContents(): string
    {
        return "<?php\n\n// Generated by phauthentic/aop-bundle: registers this directory's proxy classes for autoloading.\n\\".self::class."::register(__DIR__);\n";
    }

    public static function load(string $class): void
    {
        if (!str_starts_with($class, ProxyClassName::NAMESPACE_PREFIX)) {
            return;
        }
        foreach (self::$writers as $writer) {
            if (is_file($file = $writer->pathFor($class))) {
                require $file;

                return;
            }
        }
    }
}
